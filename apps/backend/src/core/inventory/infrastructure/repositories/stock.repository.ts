  async getAdvancedRangeStock({
    type,
    start,
    end,
  }: {
    type?: WAREHOUSE_TYPE
    start: string
    end: string
  }): Promise<StockGeneral[]> {
    let warehouses = await this.warehouseRepository.getWarehouses()
    if (type) {
      warehouses = warehouses.filter((el) => el.type == type)
    }
    if (warehouses.length == 0) return []

    const warehouseSql = warehouses.map((el) => `'${el.code}'`).join(',')
    const [initial, last]: [InitialStockDb[], LastStockDb[]] =
      await Promise.all([
        AppDataSource.query(
          `SELECT item_id,stock_last,total_last FROM inv_stock is2 WHERE is2.warehouse_id IN (${warehouseSql}) AND DATE(stock_at)="${start}" GROUP BY item_id;`,
        ),
        AppDataSource.query(
          `SELECT item_id,stock_physical,unit_value,total_value FROM inv_stock is2 WHERE is2.warehouse_id IN (${warehouseSql}) AND DATE(stock_at)="${end}" GROUP BY item_id;`,
        ),
      ])

    const rows: StockRowAllDb[] =
      await AppDataSource.query(`SELECT is2.item_id, is2.item_name,SUM(is2.quantity_in_mv) quantity_in_mv, SUM(is2.quantity_out_mv) quantity_out_mv ,SUM(is2.quantity_out_dp) quantity_out_dp ,SUM(is2.quantity_in_dp) quantity_in_dp,
SUM(is2.quantity_in_pu) quantity_in_pu,SUM(is2.quantity_out_sl) quantity_out_sl,unit_value FROM inv_stock is2
WHERE is2.warehouse_id IN (${warehouseSql}) AND stock_at BETWEEN "${start}" AND "${end}"
GROUP BY item_id;`)

    if (rows.length == 0 && initial.length == 0 && last.length == 0) return []
    const initialItemIds = initial.map((el) => el.item_id)
    const lastItemIds = last.map((el) => el.item_id)
    const rowsItemIds = rows.map((el) => el.item_id)
    const allItemIds = [...initialItemIds, ...lastItemIds, ...rowsItemIds]
    const uniqueItemIds = [...new Set(allItemIds)]
    const stock: StockGeneral[] = []

    const items = await productItemRepository.find({
      where: { id: In(uniqueItemIds) },
      relations: {
        product: {
          category: true,
        },
        presentation: true,
      },
    })
    for (const itemId of uniqueItemIds) {
      const itemDb = items.find((el) => el.id == itemId)
      const intialItem = initial.find((el) => el.item_id == itemId)
      const lastItem = last.find((el) => el.item_id == itemId)

      const row = rows.find((el) => el.item_id == itemId)

      let quantityInMv = 0
      let quantityOutMv = 0
      let quantityInDispatch = 0
      let quantityOutDispatch = 0
      let quantityInPurchase = 0
      let quantityOutSale = 0

      let initialStock = 0
      let totalInitial = 0
      let stockPhysical = 0
      let totalValue = 0
      if (row) {
        quantityInMv = Number(row.quantity_in_mv)
        quantityOutMv = Number(row.quantity_out_mv)
        quantityOutDispatch = Number(row.quantity_out_dp)
        quantityInDispatch = Number(row.quantity_in_dp)
        quantityInPurchase = Number(row.quantity_in_pu)
        quantityOutSale = Number(row.quantity_out_sl)
      }
      const unitValue = row?.unit_value ?? lastItem?.unit_value ?? 0

      if (lastItem) {
        // stockPhysical = Number(lastItem.stock_physical)
        // totalValue = Number(lastItem.total_value)
        // unitValue = Number(lastStock.unit_value)
        stockPhysical = Number(lastItem.stock_physical)
        totalValue = Number(lastItem.total_value)
      }
      if (intialItem) {
        // initialStock = Number(intialItem.stock_last)
        // current = initialStock + current
        initialStock = Number(intialItem.stock_last)
        totalInitial = Number(intialItem.total_last)
      }
      // const current=this.calculateCurrent(type==)
      // const current =
      //   quantityInMv +
      //   quantityInDispatch +
      //   quantityInPurchase -
      //   (quantityOutMv + quantityOutDispatch + quantityOutSale)
      let current = 0
      if (!type) {
        current =
          quantityInMv +
          quantityInDispatch +
          quantityInPurchase -
          (quantityOutMv + quantityOutDispatch + quantityOutSale)
      } else if (type == WAREHOUSE_TYPE.STORE) {
        current = calculateCurrent(false, {
          initialStock: initialStock,
          quantityInDispatch: quantityInDispatch,
          quantityInMv: quantityInMv,
          quantityInPurchase: quantityInPurchase,
          quantityOutDispatch: quantityOutDispatch,
          quantityOutMv: quantityOutMv,
        })
      } else if (type == WAREHOUSE_TYPE.WAREHOUSE) {
        current = calculateCurrent(true, {
          initialStock: initialStock,
          quantityInDispatch: quantityInDispatch,
          quantityInMv: quantityInMv,
          quantityInPurchase: quantityInPurchase,
          quantityOutDispatch: quantityOutDispatch,
          quantityOutMv: quantityOutMv,
        })
      }

      stock.push({
        itemId: itemId,
        categoryName: itemDb?.product?.category?.category ?? '',
        createdBy: 'sys',
        itemName: itemDb?.itemName ?? '',
        initialStock,
        totalInitial,
        measureId: itemDb?.product?.measureId ?? 0,
        presentationId: itemDb?.presentationId ?? 0,
        presentationName: itemDb?.presentation?.presentation ?? '',
        totalValue,
        unitValue: Number(unitValue),
        status: STOCK_STATUS.AUTOGENERATED,
        warehouseId: '',
        stockAt: `${start} - ${end}`,
        stockCurrent: current,
        stockPhysical,
        quantityInDispatch,
        quantityInMv,
        quantityInPurchase,
        quantityOutDispatch,
        quantityOutMv,
        quantityOutSale,
      })
    }

    return stock
  }

  async getFinalValueStock(
    warehouseCode: string,
    date: string,
  ): Promise<number> {
    const stock = await this.stockRepository.find({
      where: {
        warehouse_id: warehouseCode,
        stock_at: Raw((alias) => `DATE(${alias}) = '${date}'`),
        status: STOCK_STATUS.CLOSED as any,
      },
    })
    return stock.reduce((acc, el) => acc + Number(el.total_value), 0)
  }
  async hasBeforeStock(warehouseId: string, date: string): Promise<boolean> {
    const oneStock = await this.stockRepository.findOne({
      select: { id: true },
      where: {
        warehouse_id: warehouseId,
        stock_at: Raw((alias) => `DATE(${alias}) < '${date}'`),
        status: STOCK_STATUS.CLOSED as any,
      },
    })
    return !!oneStock
  }
