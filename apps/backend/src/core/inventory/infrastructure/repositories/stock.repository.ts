  async getRangeStock(
    warehouseCode: string,
    start: string,
    end: string,
  ): Promise<{
    stock: StockGeneral[]
    lastClosed: string | null
    warehouseName: string
  }> {
    const dates = eachDayOfInterval({
      start: parseISO(start),
      end: parseISO(end),
    }).map((el) => format(el, 'yyyy-MM-dd'))
    const warehouse = await this.warehouseRepository.getWarehouse(warehouseCode)
    if (!warehouse)
      throw new Error(
        'No se encontro sucursal con el codigo : ' + warehouseCode,
      )
    const isWarehouse = warehouse.type == WAREHOUSE_TYPE.WAREHOUSE
    const lastDateClosed = await this.getLastClosedDate(warehouseCode)
    const template = await this.templateRepository.getItemsTemplate(isWarehouse)
    const stocksDbPromises = [] as Promise<StockGeneral[]>[]

    for (const date of dates) {
      stocksDbPromises.push(
        this.stockByDateHelperRange(warehouseCode, date, {
          isWarehouse,
        }),
      )
    }
    const stocksByDate = await Promise.all(stocksDbPromises)
    // const allStocks = stocksByDate.flat()

    const stock: { [key: string]: StockGeneral } = {}

    for (let i = 0; i < stocksByDate.length; i++) {
      const stockByDate = stocksByDate[i]
      for (const stockDB of stockByDate) {
        if (!stockDB) continue
        if (!stock[stockDB.itemId]) {
          stock[stockDB.itemId] = this.createDefaultItemRange({
            start,
            end,
            warehouseCode,
            stock: stockDB,
          })
        }
        stock[stockDB.itemId].quantityInDispatch += stockDB.quantityInDispatch
        stock[stockDB.itemId].quantityOutDispatch += stockDB.quantityOutDispatch
        stock[stockDB.itemId].quantityInPurchase += stockDB.quantityInPurchase
        stock[stockDB.itemId].quantityOutSale += stockDB.quantityOutSale
        stock[stockDB.itemId].quantityInMv += stockDB.quantityInMv
        stock[stockDB.itemId].quantityOutMv += stockDB.quantityOutMv

        if (i == 0) {
          stock[stockDB.itemId].initialStock = stockDB.initialStock
          stock[stockDB.itemId].totalInitial = stockDB.totalInitial
        }
        if (i == stocksByDate.length - 1) {
          stock[stockDB.itemId].stockPhysical = stockDB.stockPhysical
          stock[stockDB.itemId].totalValue = stockDB.totalValue
          stock[stockDB.itemId].stockCurrent = this.calculateCurrent(
            isWarehouse,
            {
              ...stock[stockDB.itemId],
            },
          )
        }
      }
    }
    for (const itemTemplate of template) {
      if (!stock[itemTemplate.id]) {
        stock[itemTemplate.id] = this.itemToStockGeneral(itemTemplate, {
          date: `${start} - ${end}`,
          isWarehouse,
          warehouse: warehouseCode,
        })
      }
    }
    const allItems = Object.values(stock).sort((a, b) =>
      a.itemName.localeCompare(b.itemName),
    )

    return {
      stock: allItems,
      lastClosed: lastDateClosed,
      warehouseName: warehouse?.name ?? '',
    }
  }

