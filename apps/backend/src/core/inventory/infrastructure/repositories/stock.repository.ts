  async getLastInfoWarehouse(warehouseCode: string): Promise<{
    lastClosed: string | null
    warehouseName: string
    isWarehouse: boolean
  }> {
    const [oneStock, warehouse] = await Promise.all([
      invStockRepository.findOne({
        where: {
          warehouse_id: warehouseCode,
          status: STOCK_STATUS.CLOSED as any,
        },
        order: {
          stock_at: 'DESC',
        },
      }),
      this.warehouseRepository.getWarehouse(warehouseCode),
    ])
    if (!warehouse) {
      throw new Error(
        'No se encontro sucursal con el codigo : ' + warehouseCode,
      )
    }
    const isWarehouse = warehouse.type == WAREHOUSE_TYPE.WAREHOUSE
    return {
      lastClosed: oneStock?.stock_at?.split(' ')[0] ?? null,
      warehouseName: warehouse?.name ?? '',
      isWarehouse,
    }
  }

  async getStockByDate(
    warehouseCode: string,
    date: string,
  ): Promise<{
    stock: StockGeneral[]
    lastClosed: string | null
    warehouseName: string
    isEmpty: boolean
  }> {
    const warehouse = await this.warehouseRepository.getWarehouse(warehouseCode)
    const lastStockClosed = await this.getLastClosedDate(warehouseCode)
    const inventarios = await invStockRepository.find({
      where: {
        warehouse_id: warehouseCode,
        stock_at: Raw((alias) => `DATE(${alias})= :date `, { date }),
        status: In([
          STOCK_STATUS.CLOSED as any,
          STOCK_STATUS.AUTOGENERATED as any,
        ]),
      },
      relations: {
        item: {
          product: {
            category: true,
            measure: true,
          },
          presentation: true,
        },
      },
    })
    const itemsInStock = this.getItemsInStock(inventarios)

    let isClosed = false
    if (lastStockClosed) {
      if (lastStockClosed == date) isClosed = true
      if (lastStockClosed > date) isClosed = true
    }
    const { template, isWarehouse } =
      await this.templateRepository.getDynamicStockTemplate(warehouseCode)

    if (inventarios.length == 0) {
      if (lastStockClosed) {
        return {
          stock: [],
          lastClosed: lastStockClosed,
          warehouseName: warehouse?.name ?? '',
          isEmpty: true,
        }
      } else {
        return {
          stock: this.transformTemplate(template, {
            date,
            warehouse: warehouseCode,
            isWarehouse,
          }),
          lastClosed: lastStockClosed,
          warehouseName: warehouse?.name ?? '',
          isEmpty: true,
        }
      }
    }

    let stockClosed: StockGeneral[] | null = null
    if (!isClosed && lastStockClosed) {
      stockClosed = await this.getLastClosedStock(warehouseCode)
    }

    const allItems = this.unionItems(itemsInStock, template)
    const stock: StockGeneral[] = []
    for (const itemTemplate of allItems) {
      const itemInventario = inventarios.find(
        (el) => el.item_id == itemTemplate.id,
      )
      const beforeInitial = stockClosed?.find(
        (el) => el.itemId == itemTemplate.id,
      )

      const initialStock =
        beforeInitial?.stockPhysical ?? itemInventario?.stock_last ?? 0
      const totalLast =
        beforeInitial?.totalValue ?? itemInventario?.total_value ?? 0

      const quantityInMv = itemInventario?.quantity_in_mv ?? 0
      const quantityOutMv = itemInventario?.quantity_out_mv ?? 0
      const quantityInDispatch = itemInventario?.quantity_in_dp ?? 0
      const quantityOutDispatch = itemInventario?.quantity_out_dp ?? 0
      const quantityInPurchase = itemInventario?.quantity_in_pu ?? 0
      const quantityOutSale = itemInventario?.quantity_out_sl ?? 0

      const stockCurrent = this.calculateCurrent(isWarehouse, {
        initialStock,
        quantityInMv,
        quantityOutMv,
        quantityInDispatch,
        quantityOutDispatch,
        quantityInPurchase,
      })

      stock.push({
        itemId: itemTemplate.id,
        totalInitial: totalLast,
        categoryName: itemTemplate.categoryName,
        itemName: itemTemplate.name,
        presentationId: itemTemplate.presentationId,
        presentationName: itemTemplate.presentationName,
        measureId: itemTemplate.measureId,
        warehouseId: warehouseCode,
        stockAt: date,
        initialStock,
        stockCurrent,
        stockPhysical: itemInventario?.stock_physical ?? 0,
        unitValue: itemInventario
          ? itemInventario.unit_value
          : isWarehouse
            ? itemTemplate.warehousePrice
            : itemTemplate.storePrice,
        totalValue: itemInventario?.total_value ?? 0,
        createdBy: itemInventario?.created_by ?? 'sys',
        status: isClosed ? STOCK_STATUS.CLOSED : STOCK_STATUS.AUTOGENERATED,
        quantityInMv,
        quantityOutMv,
        quantityInDispatch,
        quantityInPurchase,
        quantityOutDispatch,
        quantityOutSale,
      } satisfies StockGeneral)
    }

    return {
      lastClosed: lastStockClosed,
      stock: stock,
      warehouseName: warehouse?.name ?? '',
      isEmpty: false,
    }
  }

