  private getItemsInStock(inventario: InvStock[]): Item[] {
    const itemInStockDb = inventario.map((el) => el.item)
    const itemsInStock: Item[] = itemInStockDb.map(
      (el) =>
        ({
          id: el.id,
          categoryName: el.product?.category?.category ?? '',
          measureId: el.product?.measureId ?? -1,
          name: el.itemName,
          presentationId: el.presentationId,
          presentationName: el.presentation?.presentation ?? '',
          productId: el.productId,
          storePrice: el.unitPrice,
          warehousePrice: el.unitCost,
        }) satisfies Item,
    )
    return itemsInStock
  }

  private unionItems(items1: Item[], items2: Item[]): Item[] {
    const items = [...items1, ...items2]
    const uniqueItems: Item[] = items.reduce((acc, item) => {
      if (!acc.some((el) => el.id == item.id)) acc.push(item)
      return acc
    }, [] as Item[])

    return uniqueItems
  }

  async getLastClosedDate(warehouseCode: string): Promise<string | null> {
    const inventario = await invStockRepository.findOne({
      where: {
        warehouse_id: warehouseCode,
        status: STOCK_STATUS.CLOSED as any,
      },
      order: {
        stock_at: 'DESC',
      },
    })
    if (!inventario) return null
    return inventario.stock_at.split(' ')[0]
  }

  async getLastClosedStock(
    warehouseCode: string,
  ): Promise<StockGeneral[] | null> {
    const lastStockClosed = await this.getLastClosedDate(warehouseCode)
    if (!lastStockClosed) return null
    const data = await this.getStockByDate(warehouseCode, lastStockClosed)
    return data.stock
  }

